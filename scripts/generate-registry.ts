import { format } from 'prettier';
import { existsSync } from 'node:fs';
import { readdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import type {
	PuzzleFamilyEntry,
	PuzzleManifest,
	PuzzleMetadata,
	PuzzlePresentation,
	PuzzleVariant
} from '../src/lib/engine/contract.js';
import { validateEnding } from './validate-ending.js';
type ClientPuzzleVariant = Omit<PuzzleVariant, 'leaderboardGroups'>;
type ClientPuzzleMetadata = Omit<PuzzleMetadata, 'presentation' | 'variants'> & {
	presentation: Omit<PuzzlePresentation, 'groups'>;
	variants?: readonly ClientPuzzleVariant[];
};
const directories = (await readdir('src/lib/puzzles', { withFileTypes: true }))
	.filter((entry) => entry.isDirectory())
	.map((entry) => entry.name)
	.sort();
const ids = new Set<string>();
const puzzles: {
	directory: string;
	id: string;
	family: PuzzleFamilyEntry;
	metadata: ClientPuzzleMetadata;
	messages: Readonly<Record<string, string>>;
}[] = [];
for (const directory of directories) {
	const { manifest } = await import(resolve('src/lib/puzzles', directory, 'manifest.ts'));
	if (typeof manifest?.id !== 'string' || !manifest.id || ids.has(manifest.id))
		throw new Error(`Missing or duplicate puzzle id: ${directory}`);
	ids.add(manifest.id);
	validateEnding(manifest.id, manifest.ending, manifest.messages);
	const family: PuzzleFamilyEntry = {
		id: manifest.id,
		weight: manifest.weight ?? 1,
		enabled: manifest.enabled ?? true,
		orientation: manifest.orientation ?? 'any',
		selectionOrder: manifest.selectionOrder,
		minViewportWidth: manifest.minViewportWidth,
		minViewportHeight: manifest.minViewportHeight
	};
	if (
		!Number.isSafeInteger(family.weight) ||
		family.weight < 0 ||
		family.weight > 10000 ||
		typeof family.enabled !== 'boolean' ||
		!['any', 'portrait', 'landscape'].includes(family.orientation) ||
		[family.minViewportWidth, family.minViewportHeight, family.selectionOrder].some(
			(value) => value !== undefined && (!Number.isSafeInteger(value) || value < 0)
		)
	)
		throw new Error(`Invalid selector metadata: ${directory}`);
	const {
		engineVersion,
		titleAfterEntrance,
		scoring,
		ending,
		presentation,
		variants
	}: PuzzleManifest = manifest;
	const variantIds = new Set<string>();
	for (const variant of variants ?? []) {
		if (
			!variant.id.startsWith(`${manifest.id}:`) ||
			variantIds.has(variant.id) ||
			!manifest.messages[variant.name] ||
			!Number.isSafeInteger(variant.weight) ||
			variant.weight <= 0 ||
			variant.weight > 10000 ||
			!Number.isSafeInteger(variant.maxMoves) ||
			variant.maxMoves <= 0 ||
			variant.maxMoves > manifest.maxMoves ||
			(variant.maxSeconds !== undefined &&
				(!Number.isSafeInteger(variant.maxSeconds) ||
					variant.maxSeconds <= 0 ||
					variant.maxSeconds > 7200))
		)
			throw new Error(`Invalid variant metadata: ${directory}`);
		variantIds.add(variant.id);
		if (variant.ending) validateEnding(manifest.id, variant.ending, manifest.messages);
	}
	const { groups, ...clientPresentation } = presentation;
	void groups;
	const clientVariants = variants?.map(({ leaderboardGroups, ...clientVariant }) => {
		void leaderboardGroups;
		return clientVariant;
	});

	puzzles.push({
		directory,
		id: manifest.id,
		family,
		metadata: {
			engineVersion,
			titleAfterEntrance,
			scoring,
			variants: clientVariants,
			ending,
			presentation: clientPresentation,
			backdropPieces: manifest.backdropPieces
		},
		messages: manifest.messages
	});
}
const header = '// Generated by scripts/generate-registry.ts. Do not edit by hand.';
const catalog = [header, "import type { PuzzleId, PuzzleManifest } from './engine/contract.js';"];
for (const [index, { directory }] of puzzles.entries()) {
	catalog.push(
		`import { manifest as manifest${index} } from './puzzles/${directory}/manifest.js';`
	);
}
const known = puzzles.map(({ id }, i) => `${JSON.stringify(id)}: typeof manifest${i}`).join(';');
catalog.push(
	`export const catalog: Record<PuzzleId, PuzzleManifest> & {${known}} = {${puzzles.map(({ id }, i) => `[${JSON.stringify(id)}]: manifest${i}`).join(',')}};`,
	"export { puzzleMessages } from './puzzle-messages.js';"
);
const registry = [
	header,
	"import type { Component, ComponentProps, Snippet } from 'svelte';",
	"import type RoundStage from './components/RoundStage.svelte';",
	"import type { PuzzleId, PuzzleManifest } from './engine/contract.js';",
	"import type { PuzzleViewProps } from './ui/puzzle-view.js';",
	`export const puzzleViews: Record<PuzzleId, () => Promise<{ default: Component<PuzzleViewProps> }>> = {${puzzles.map(({ directory, id }) => `${JSON.stringify(id)}: () => import('./puzzles/${directory}/View.svelte')`).join(',')}};`,
	"export type PuzzleStage = Component<ComponentProps<typeof RoundStage> & { footerContent?: Snippet }, Pick<RoundStage, 'present' | 'stop' | 'measureFrame'>>;",
	`export const puzzleStages: Partial<Record<PuzzleId, () => Promise<{ default: PuzzleStage }>>> = {${puzzles
		.filter(({ directory }) => existsSync(resolve('src/lib/puzzles', directory, 'Stage.svelte')))
		.map(
			({ directory, id }) =>
				`${JSON.stringify(id)}: () => import('./puzzles/${directory}/Stage.svelte')`
		)
		.join(',')}};`,
	'// Each current pool generates its existing procedural variants through createRound.',
	`export const puzzlePools: Record<PuzzleId, () => Promise<{ manifest: PuzzleManifest }>> = {${puzzles.map(({ directory, id }) => `${JSON.stringify(id)}: () => import('./puzzles/${directory}/manifest.js')`).join(',')}};`
];
const familyIndex = [
	header,
	"import type { PuzzleFamilyEntry } from './engine/contract.js';",
	`export const familyIndex: readonly PuzzleFamilyEntry[] = ${JSON.stringify(puzzles.map(({ family }) => family).sort((a, b) => (a.selectionOrder ?? Number.MAX_SAFE_INTEGER) - (b.selectionOrder ?? Number.MAX_SAFE_INTEGER)))};`
];
const metadata = [
	header,
	"import type { PuzzleId, PuzzleMetadata, PuzzlePresentation, PuzzleVariant } from './engine/contract.js';",
	"export type ClientPuzzleVariant = Omit<PuzzleVariant, 'leaderboardGroups'>;",
	"export type ClientPuzzleMetadata = Omit<PuzzleMetadata, 'presentation' | 'variants'> & { presentation: Omit<PuzzlePresentation, 'groups'>; variants?: readonly ClientPuzzleVariant[] };",
	`const metadata = {${puzzles.map(({ id, metadata }) => `[${JSON.stringify(id)}]: ${JSON.stringify(metadata)}`).join(',')}} as const;`,
	'export const puzzleMetadata: Record<PuzzleId, ClientPuzzleMetadata> & typeof metadata = metadata;'
];
const messages = [
	header,
	`export const puzzleMessages = ${JSON.stringify(Object.assign({}, ...puzzles.map(({ messages }) => messages)))} as const;`
];
for (const [file, lines] of [
	['catalog', catalog],
	['registry', registry],
	['family-index', familyIndex],
	['puzzle-metadata', metadata],
	['puzzle-messages', messages]
] as const) {
	await writeFile(
		`src/lib/${file}.ts`,
		await format(lines.join('\n'), {
			parser: 'typescript',
			useTabs: true,
			singleQuote: true,
			trailingComma: 'none',
			printWidth: 100
		})
	);
}
