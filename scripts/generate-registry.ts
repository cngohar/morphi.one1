import { format } from 'prettier';
import { readdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { validateEnding } from './validate-ending.js';
const directories = (await readdir('src/lib/puzzles', { withFileTypes: true }))
	.filter((entry) => entry.isDirectory())
	.map((entry) => entry.name)
	.sort();
const ids = new Set<string>();
const puzzles: { directory: string; id: string }[] = [];
for (const directory of directories) {
	const { manifest } = await import(resolve('src/lib/puzzles', directory, 'manifest.ts'));
	if (typeof manifest?.id !== 'string' || !manifest.id || ids.has(manifest.id))
		throw new Error(`Missing or duplicate puzzle id: ${directory}`);
	ids.add(manifest.id);
	validateEnding(manifest.id, manifest.ending, manifest.messages);
	puzzles.push({ directory, id: manifest.id });
}
const header = '// Generated by scripts/generate-registry.ts. Do not edit by hand.';
const catalog = [header, "import type { PuzzleId, PuzzleManifest } from './engine/contract.js';"];
for (const [index, { directory }] of puzzles.entries()) {
	catalog.push(
		`import { manifest as manifest${index} } from './puzzles/${directory}/manifest.js';`
	);
}
const known = puzzles.map(({ id }, i) => `${JSON.stringify(id)}: typeof manifest${i}`).join(';');
catalog.push(
	`export const catalog: Record<PuzzleId, PuzzleManifest> & {${known}} = {${puzzles.map(({ id }, i) => `[${JSON.stringify(id)}]: manifest${i}`).join(',')}};`,
	`export const puzzleMessages = { ${puzzles.map((_, i) => `...manifest${i}.messages`).join(',')} } as const;`
);
const registry = [
	header,
	"import type { Component } from 'svelte';",
	"import type { PuzzleId } from './engine/contract.js';",
	"import type { PuzzleViewProps } from './ui/puzzle-view.js';",
	"export { catalog, puzzleMessages } from './catalog.js';",
	`export const puzzleViews: Record<PuzzleId, () => Promise<{ default: Component<PuzzleViewProps> }>> = {${puzzles.map(({ directory, id }) => `${JSON.stringify(id)}: () => import('./puzzles/${directory}/View.svelte')`).join(',')}};`
];
for (const [file, lines] of [
	['catalog', catalog],
	['registry', registry]
] as const) {
	await writeFile(
		`src/lib/${file}.ts`,
		await format(lines.join('\n'), {
			parser: 'typescript',
			useTabs: true,
			singleQuote: true,
			trailingComma: 'none',
			printWidth: 100
		})
	);
}
